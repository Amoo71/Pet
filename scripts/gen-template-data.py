#!/usr/bin/env python3
"""Regenerate src/core/template-data.js from the device-verified PosterKit template of
github.com/iceorange-dev/tendies-wallpaper-skill (MIT).

usage: python3 scripts/gen-template-data.py <path-to-tendies-wallpaper-skill>
"""
import sys, os, plistlib, base64, json

root = os.path.join(sys.argv[1], 'template/descriptors/99990000-0000-0000-0000-000000000000')
files = {}
for dp, _, names in os.walk(root):
    for n in names:
        rel = os.path.relpath(os.path.join(dp, n), root)
        if not rel.endswith('Wallpaper.plist'):
            files[rel] = open(os.path.join(dp, n), 'rb').read()

# iOS 27 depth + motion switches (same as tendies_kit.package)
RENDER_CLASS = {"$classname": "PRPosterRenderingConfiguration", "$classes": ["PRPosterRenderingConfiguration", "NSObject"]}
EFFECTS_ON = {"depthEffectDisabled": False, "motionEffectsDisabled": False}
k = 'versions/0/contents/.com.apple.posterkit.provider.contents.configurableOptions.plist'
opts = plistlib.loads(files[k]); objs = opts['$objects']; r = objs[opts['$top']['root'].data]
if 'preferredRenderingConfiguration' in r:
    objs[r['preferredRenderingConfiguration'].data].update(EFFECTS_ON)
else:
    cid = len(objs); objs.append(dict(RENDER_CLASS))
    r['preferredRenderingConfiguration'] = plistlib.UID(len(objs)); objs.append({"$class": plistlib.UID(cid), **EFFECTS_ON})
if 'role' not in r:
    r['role'] = plistlib.UID(len(objs)); objs.append('PRPosterRoleLockScreen')
files[k] = plistlib.dumps(opts, fmt=plistlib.FMT_BINARY, sort_keys=False)
files['versions/0/com.apple.posterkit.provider.instance.renderingConfiguration.plist'] = plistlib.dumps(
    {"$version": 100000, "$archiver": "NSKeyedArchiver", "$top": {"root": plistlib.UID(1)},
     "$objects": ["$null", {"$class": plistlib.UID(2), **EFFECTS_ON}, dict(RENDER_CLASS)]},
    fmt=plistlib.FMT_BINARY, sort_keys=False)
for gen in ['com.apple.posterkit.provider.descriptor.identifier', 'versions/0/contents/com.apple.posterkit.provider.contents.userInfo']:
    files.pop(gen, None)

data = {k: base64.b64encode(v).decode() for k, v in sorted(files.items())}
out = [
    '// Device-verified PosterKit metadata for ParameterizedCA wallpapers (iOS 26 / 27).',
    '// Source: github.com/iceorange-dev/tendies-wallpaper-skill (MIT) template, with the iOS 27',
    '// depth/motion rendering configuration pre-applied (see docs/FORMAT.md). Paths are relative to',
    '// descriptors/<UUID>/. Generated by scripts/gen-template-data.py — do not edit by hand.',
    'export const PCA_WALLPAPER_DIR = "7400.WWDC_2022-390w-844h@3x~iphone.wallpaper";',
    'export const PCA_FILES = ' + json.dumps(data, indent=2) + ';', '']
dst = os.path.join(os.path.dirname(__file__), '..', 'src', 'core', 'template-data.js')
open(dst, 'w').write('\n'.join(out))
print('wrote', dst, len(data), 'files')
